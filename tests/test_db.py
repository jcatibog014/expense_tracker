import pytest

from gastos import db


def test_postgres_placeholders(app):
    with app.app_context():
        app.config["DATABASE_URL"] = "postgresql://example"
        assert db._sql("SELECT * FROM t WHERE a = ? AND b LIKE '50%'") == (
            "SELECT * FROM t WHERE a = %s AND b LIKE '50%%'"
        )
        sql = db.schema_sql()
        assert "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in sql
        assert "id INTEGER PRIMARY KEY," not in sql


def test_sqlite_sql_is_unchanged(app):
    with app.app_context():
        if db.is_postgres():
            pytest.skip("only for SQLite")
        assert db._sql("SELECT ? AS a") == "SELECT ? AS a"


def test_query_returns_dicts(app):
    with app.app_context():
        rows = db.query("SELECT username FROM users ORDER BY username")
        assert rows == [{"username": "juan"}]
        assert db.query_one("SELECT username FROM users WHERE username = ?", ("nobody",)) is None


def test_insert_returns_the_new_id(app, owner_id):
    with app.app_context():
        new_id = db.insert(
            "INSERT INTO accounts (user_id, name, kind) VALUES (?, ?, ?) RETURNING id",
            (owner_id, "Maya", "ewallet"),
        )
        assert db.query_one("SELECT name FROM accounts WHERE id = ?", (new_id,)) == {"name": "Maya"}


def test_without_commit_nothing_is_saved(app, owner_id):
    with app.app_context():
        db.execute("DELETE FROM accounts WHERE user_id = ?", (owner_id,))
    with app.app_context():  # a new connection
        assert db.query_one("SELECT COUNT(*) AS n FROM accounts WHERE user_id = ?", (owner_id,))["n"] == 3


def test_the_database_checks_its_rules(app, owner_id):
    with app.app_context():
        account = db.query_one("SELECT id FROM accounts WHERE user_id = ? AND name = 'Cash'", (owner_id,))["id"]
        bad_rows = [
            # amount must be above zero
            ("expense", 0, account, None, 1),
            # an expense needs a category
            ("expense", 100, account, None, None),
            # a transfer needs a "to" wallet and no category
            ("transfer", 100, account, None, 1),
            # unknown kind
            ("gift", 100, account, None, 1),
        ]
        for kind, amount, account_id, to_account_id, category_id in bad_rows:
            with pytest.raises(Exception):
                db.execute(
                    """INSERT INTO transactions
                           (user_id, kind, amount, date, account_id, to_account_id, category_id)
                       VALUES (?, ?, ?, '2026-10-01', ?, ?, ?)""",
                    (owner_id, kind, amount, account_id, to_account_id, category_id),
                )
            db.get_db().rollback()  # Postgres needs this after an error


def test_a_used_wallet_cannot_be_deleted(app, owner_id):
    with app.app_context():
        account = db.query_one("SELECT id FROM accounts WHERE user_id = ? AND name = 'Cash'", (owner_id,))["id"]
        category = db.query_one("SELECT id FROM categories WHERE user_id = ? AND name = 'Food'", (owner_id,))["id"]
        db.execute(
            """INSERT INTO transactions (user_id, kind, amount, date, account_id, category_id)
               VALUES (?, 'expense', 15000, '2026-10-01', ?, ?)""",
            (owner_id, account, category),
        )
        with pytest.raises(Exception):  # FOREIGN KEY rule
            db.execute("DELETE FROM accounts WHERE id = ?", (account,))


