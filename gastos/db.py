"""The database: SQLite on your computer, PostgreSQL (Neon) on the live site.

We write plain SQL and send it through the small functions below, so the
rest of the app doesn't care which database it talks to:

    query("SELECT * FROM accounts WHERE user_id = ?", (user_id,))  -> list of dicts
    query_one(...)                                                -> one dict or None
    execute("UPDATE ...", (...))                                  -> nothing
    insert("INSERT ... RETURNING id", (...))                      -> the new id
    commit()                                                    -> save the changes

Two rules keep the SQL portable:
- Use ? for values. SQLite wants ?, psycopg (Postgres) wants %s, so _sql() swaps them.
- Never put a value inside the SQL text. Pass it as a parameter, so the
  database treats it as data and not as code (this stops "SQL injection").

Changes are saved only after commit(). If a request fails half way, the
connection closes without a commit and nothing is half-saved.
"""
import sqlite3
from pathlib import Path

import click
from flask import current_app, g
from flask.cli import with_appcontext

SCHEMA = Path(__file__).parent / "schema.sql"


def is_postgres():
    return bool(current_app.config.get("DATABASE_URL"))


def connect():
    url = current_app.config.get("DATABASE_URL")
    if url:
        # Imported here, so local SQLite use works even without psycopg.
        import psycopg
        from psycopg.rows import dict_row

        # prepare_threshold=None: no "prepared statements", which Neon's
        # connection pooler doesn't keep between requests.
        return psycopg.connect(url, row_factory=dict_row, prepare_threshold=None, connect_timeout=15)

    path = Path(current_app.config["DATABASE"])
    path.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(path)
    connection.row_factory = sqlite3.Row  # rows we can read by column name
    # SQLite ignores FOREIGN KEY rules unless we switch them on (Postgres always checks them).
    connection.execute("PRAGMA foreign_keys = ON")
    return connection


def get_db():
    """One connection per request, opened the first time we need it."""
    if "db" not in g:
        g.db = connect()
    return g.db


def close_db(error=None):
    connection = g.pop("db", None)
    if connection is not None:
        connection.close()


def _sql(sql):
    """Turn our ?-style SQL into what the database wants."""
    if is_postgres():
        # psycopg uses % for its placeholders, so a real % must be written %%.
        return sql.replace("%", "%%").replace("?", "%s")
    return sql


def query(sql, params=()):
    cursor = get_db().execute(_sql(sql), params)
    return [dict(row) for row in cursor.fetchall()]


def query_one(sql, params=()):
    cursor = get_db().execute(_sql(sql), params)
    row = cursor.fetchone()
    return dict(row) if row is not None else None


def execute(sql, params=()):
    get_db().execute(_sql(sql), params)


def execute_many(sql, rows):
    """Run the same SQL once per row. Much faster than a loop over the network to Neon."""
    get_db().cursor().executemany(_sql(sql), rows)


def insert(sql, params=()):
    """Run an INSERT ... RETURNING id and give back the new row's id."""
    return query_one(sql, params)["id"]


def commit():
    get_db().commit()


def schema_sql():
    """schema.sql, with the one line that differs between the two databases.

    SQLite numbers rows by itself when a column is INTEGER PRIMARY KEY.
    Postgres needs to be told: GENERATED BY DEFAULT AS IDENTITY.
    """
    sql = SCHEMA.read_text(encoding="utf-8")
    if is_postgres():
        sql = sql.replace(
            "id INTEGER PRIMARY KEY",
            "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        )
    return sql


# Upgrades ("migrations") for databases made before a change to schema.sql,
# like the live one on Neon. Each runs once, in order, and the
# schema_version table remembers how many have run. A new database from
# init-db already has everything, so init_db() marks them all as done.
# Never change one that has run on the live site: add a new one at the end,
# and change schema.sql the same way.
MIGRATIONS = [
    # 1: Ikapu. The ikapu wallet flag, the link from a set-aside to its
    # income, and an Ikapu wallet and spending category for every user.
    [
        "ALTER TABLE accounts ADD COLUMN is_ikapu INTEGER NOT NULL DEFAULT 0",
        "ALTER TABLE transactions ADD COLUMN tithe_of INTEGER REFERENCES transactions (id) ON DELETE CASCADE",
        # SQLite wants a WHERE in INSERT ... SELECT ... ON CONFLICT, even one that is always true.
        """INSERT INTO accounts (user_id, name, kind) SELECT id, 'Ikapu', 'cash' FROM users WHERE 1 = 1
           ON CONFLICT (user_id, name) DO NOTHING""",
        "UPDATE accounts SET is_ikapu = 1, archived = 0 WHERE name = 'Ikapu'",
        """INSERT INTO categories (user_id, name, kind, color) SELECT id, 'Ikapu', 'expense', 'violet'
           FROM users WHERE 1 = 1 ON CONFLICT (user_id, name, kind) DO NOTHING""",
    ],
]


def schema_version():
    """How many MIGRATIONS this database has (0 for one made before they existed)."""
    execute("CREATE TABLE IF NOT EXISTS schema_version (version INTEGER NOT NULL)")
    row = query_one("SELECT version FROM schema_version")
    return row["version"] if row else 0


def set_schema_version(version):
    execute("DELETE FROM schema_version")
    execute("INSERT INTO schema_version (version) VALUES (?)", (version,))


def upgrade_db():
    """Run the migrations this database doesn't have yet. Returns (old, new) version.

    Each migration is saved (committed) on its own, so if one fails, the
    ones before it stay done and the next run starts at the failed one.
    """
    old = schema_version()
    for number, statements in enumerate(MIGRATIONS[old:], start=old + 1):
        for sql in statements:
            execute(sql)
        set_schema_version(number)
        commit()
    return old, len(MIGRATIONS)


def init_db():
    """Delete every table and make them again, empty."""
    connection = get_db()
    if is_postgres():
        connection.execute(schema_sql())  # psycopg runs several statements when there are no parameters
    else:
        connection.executescript(schema_sql())
    set_schema_version(len(MIGRATIONS))  # a new database is already up to date
    connection.commit()


@click.command("init-db")
@with_appcontext
@click.option("--yes", is_flag=True, help="Don't ask before deleting everything.")
def init_db_command(yes):
    """Make empty tables. WARNING: this deletes all data first."""
    if not yes:
        click.confirm("This deletes ALL data in the database. Continue?", abort=True)
    init_db()
    click.echo("The database is ready (empty).")


@click.command("upgrade-db")
@with_appcontext
def upgrade_db_command():
    """Bring the tables up to date, keeping all data. Safe to run any time."""
    old, new = upgrade_db()
    if old == new:
        click.echo(f"The database is up to date (version {new}).")
    else:
        click.echo(f"Upgraded the database from version {old} to {new}.")


def init_app(app):
    app.teardown_appcontext(close_db)
    app.cli.add_command(init_db_command)
    app.cli.add_command(upgrade_db_command)
